/* base arriendo - DBISAM 4 */

CREATE TABLE IF NOT EXISTS "AUTOS"
(
   "PATENTE" VARCHAR(8) NOT NULL,
   "MARCA" VARCHAR(30),
   "MODELO" VARCHAR(30),
   "CATEGORIA" CHAR(1),
   "TARIFA_DIA" MONEY,
   "KM_ACTUAL" INTEGER,
PRIMARY KEY ("PATENTE") COMPRESS NONE
);

CREATE TABLE IF NOT EXISTS "CLIENTES"
(
   "ID_CLIENTE" INTEGER NOT NULL,
   "RUT" VARCHAR(12),
   "NOMBRE" VARCHAR(60),
   "FECHA_NACIMIENTO" DATE,
PRIMARY KEY ("ID_CLIENTE") COMPRESS NONE
);

CREATE TABLE IF NOT EXISTS "ARRIENDOS"
(
   "ID_ARRIENDO" AUTOINC,
   "PATENTE" VARCHAR(8),
   "ID_CLIENTE" INTEGER,
   "FECHA_SALIDA" TIMESTAMP,
   "FECHA_PACTADA" TIMESTAMP,
   "TOTAL" MONEY,
   "USUARIO" VARCHAR(15),
PRIMARY KEY ("ID_ARRIENDO") COMPRESS NONE
);
